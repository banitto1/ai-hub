import { _electron as electron } from 'playwright';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
const temp=mkdtempSync(join(tmpdir(),'aihub-desktop-'));
const output=resolve('desktop-validation');mkdirSync(output,{recursive:true});
const env={...process.env,AI_HUB_DATA_DIR:join(temp,'data'),AI_HUB_PROFILE_DIR:join(temp,'profile')};
delete env.ELECTRON_RUN_AS_NODE;
let app;
const results=[];
try{
 app=await electron.launch({executablePath:resolve('win-app/AI Hub.exe'),env,timeout:60000});
 const page=await app.firstWindow();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.getByRole('heading',{name:'Ваше пространство для ИИ'}).waitFor({timeout:60000});
 assert.equal(await page.locator('html').getAttribute('lang'),'ru');
 assert.equal(await page.getByText('Открыть и войти',{exact:true}).count(),3);
 await page.waitForTimeout(350);
 console.log('layout',await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,dpr:devicePixelRatio,main:document.querySelector('.main-column').getBoundingClientRect().toJSON()})));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'no horizontal overflow');
 const nativeShot=await app.evaluate(async({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'));
 writeFileSync(join(output,'overview-ru.png'),Buffer.from(nativeShot,'base64'));results.push('Native launch and Russian overview');
 await page.getByRole('textbox',{name:'Черновик запроса'}).fill('Проверка сохранения черновика');
 await page.getByRole('navigation').getByRole('button',{name:'Задачи',exact:true}).click();
 await page.getByRole('textbox',{name:'Новая задача'}).fill('Проверить настольную версию');
 await page.getByRole('button',{name:'Добавить',exact:true}).click();
 await page.getByText('Проверить настольную версию',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Изменить статус'}).click();
 await page.waitForFunction(()=>document.querySelector('.list-row.done'));
 results.push('Task create and completion persisted through local API');
 await page.getByRole('navigation').getByRole('button',{name:'Инструкции'}).click();
 await page.getByLabel('Название',{exact:true}).fill('Проверка');await page.getByLabel('Инструкция',{exact:true}).fill('Отвечай по-русски.');
 await page.getByRole('button',{name:'Сохранить',exact:true}).click();await page.getByRole('heading',{name:'Проверка',exact:true}).waitFor();results.push('Instructions create');
 await page.getByRole('navigation').getByRole('button',{name:'Файлы',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles({name:'test.txt',mimeType:'text/plain',buffer:Buffer.from('desktop upload')});
 await page.locator('.list-row').filter({hasText:'test.txt'}).waitFor();results.push('File upload');
 await page.getByRole('navigation').getByRole('button',{name:'Настройки',exact:true}).click();
 await page.getByLabel('Масштаб',{exact:true}).selectOption('1.3');
 await page.getByRole('switch',{name:'Анимации'}).click();
 await page.waitForFunction(()=>document.documentElement.dataset.motion==='off');
 await page.screenshot({path:join(output,'settings-ru.png'),fullPage:true,animations:'disabled',scale:'css'});
 await page.getByLabel('Language',{exact:true}).selectOption('en');
 await page.getByRole('heading',{name:'Appearance',exact:true}).waitFor();
 assert.equal(await page.locator('html').getAttribute('lang'),'en');results.push('RU/EN, 130% zoom and reduced motion');
 // IPC rejects arbitrary service IDs; remote sites never receive the desktop preload.
 const rejected=await page.evaluate(async()=>{try{await window.desktop.openService('file:///C:/Windows');return false;}catch{return true;}});assert.equal(rejected,true);results.push('Service allowlist rejects arbitrary URLs');
 assert.deepEqual(errors,[]);
 await app.close();app=null;
 app=await electron.launch({executablePath:resolve('win-app/AI Hub.exe'),env,timeout:60000});
 const again=await app.firstWindow();await again.getByRole('heading',{name:'Your space for AI'}).waitFor({timeout:60000});
 assert.equal(await again.getByRole('textbox',{name:'Prompt draft'}).inputValue(),'Проверка сохранения черновика');
 assert.equal(await again.locator('html').getAttribute('data-motion'),'off');
 await again.getByRole('navigation').getByRole('button',{name:'Tasks',exact:true}).click();await again.getByText('Проверить настольную версию',{exact:true}).waitFor();
 results.push('Preferences, draft and database survive application restart');
 writeFileSync(join(output,'results.json'),JSON.stringify({passed:results,testData:temp},null,2));console.log(JSON.stringify(results,null,2));
}finally{await app?.close();}
